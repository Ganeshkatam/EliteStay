/*
==================================================
Migration: Phase 1 Domain Evolution (9.8/10 Architecture)
Purpose:
  1. Normalize property_types as a SMALLINT reference table & seed initial catalog.
  2. Introduce localities table as a geographic entity under cities with unique constraints.
  3. Alter listings to add property_type_id and locality_id FK columns & backfill data.
  4. Extract listing_capacity into a dedicated table with inherited RLS & backfill from max_occupants.
==================================================
*/

-- 1. Create property_types reference table
CREATE TABLE IF NOT EXISTS public.property_types (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    description TEXT,
    icon TEXT,
    display_order INTEGER DEFAULT 0 NOT NULL,
    is_active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

ALTER TABLE public.property_types ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read access on property_types" ON public.property_types;
CREATE POLICY "Allow public read access on property_types"
    ON public.property_types
    FOR SELECT
    USING (is_active = true OR public.is_admin());

DROP POLICY IF EXISTS "Allow admin management on property_types" ON public.property_types;
CREATE POLICY "Allow admin management on property_types"
    ON public.property_types
    FOR ALL
    USING (public.is_admin());

DROP TRIGGER IF EXISTS trigger_property_types_updated_at ON public.property_types;
CREATE OR REPLACE TRIGGER trigger_property_types_updated_at
    BEFORE UPDATE ON public.property_types
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

