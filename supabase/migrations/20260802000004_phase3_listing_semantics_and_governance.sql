-- 3. Create listing_features Table (Physical Characteristics)
CREATE TABLE IF NOT EXISTS public.listing_features (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    listing_id UUID NOT NULL UNIQUE REFERENCES public.listings(id) ON DELETE CASCADE,
    floor_number INTEGER,
    total_floors INTEGER,
    area NUMERIC,
    area_unit VARCHAR(20) DEFAULT 'sqft' NOT NULL,
    facing_direction_id SMALLINT REFERENCES public.facing_directions(id),
    balcony_count SMALLINT DEFAULT 0 NOT NULL,
    has_lift BOOLEAN DEFAULT false NOT NULL,
    has_attached_bathroom BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    CONSTRAINT check_balcony_count CHECK (balcony_count >= 0),
    CONSTRAINT check_area CHECK (area IS NULL OR area > 0),
    CONSTRAINT check_area_unit CHECK (area_unit IN ('sqft', 'sqm', 'sqyd', 'acre', 'hectare'))
);

CREATE INDEX IF NOT EXISTS idx_listing_features_listing_id ON public.listing_features(listing_id);
CREATE INDEX IF NOT EXISTS idx_listing_features_facing_direction_id ON public.listing_features(facing_direction_id);

ALTER TABLE public.listing_features ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow read access inherited from listings on features" ON public.listing_features;
CREATE POLICY "Allow read access inherited from listings on features"
    ON public.listing_features FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM public.listings l
            WHERE l.id = listing_features.listing_id
              AND (l.status = 'published' OR public.is_listing_owner(l.id) OR public.is_admin())
        )
    );

DROP POLICY IF EXISTS "Allow owners to manage listing features" ON public.listing_features;
CREATE POLICY "Allow owners to manage listing features"
    ON public.listing_features FOR ALL
    USING (public.is_listing_owner(listing_id) OR public.is_admin())
    WITH CHECK (public.is_listing_owner(listing_id) OR public.is_admin());

DROP TRIGGER IF EXISTS trigger_listing_features_updated_at ON public.listing_features;
CREATE OR REPLACE TRIGGER trigger_listing_features_updated_at
    BEFORE UPDATE ON public.listing_features
    FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();


-- 4. Create listing_rules Table (Operational Policies)
