/*
==================================================
Migration: Phase 3 Listing Semantics & Reference Data Governance (10/10 Architecture)
Purpose:
  1. Enforce standard Reference Data Governance across property_types, accommodation_types, and amenities (slug, icon, display_order, is_active, description).
  2. Create facing_directions reference lookup table for orientation and Vaastu filtering.
  3. Create listing_features 1-to-1 child table (physical characteristics like balcony_count, floor, orientation, and unit-agnostic area).
  4. Create listing_rules 1-to-1 child table (operational policies tailored to Indian co-living with paired interval checks).
  5. Create listing_rule_notes child table for editable, ordered custom house policies.
  6. Establish inherited RLS policies across all new listing semantics tables.
==================================================
*/

