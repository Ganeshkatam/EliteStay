-- 2. Create facing_directions Reference Table
CREATE TABLE IF NOT EXISTS public.facing_directions (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    description TEXT,
    icon TEXT,
    display_order INTEGER DEFAULT 0 NOT NULL,
    is_active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

ALTER TABLE public.facing_directions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read access on facing_directions" ON public.facing_directions;
CREATE POLICY "Allow public read access on facing_directions"
    ON public.facing_directions FOR SELECT
    USING (is_active = true OR public.is_admin());

DROP POLICY IF EXISTS "Allow admin management on facing_directions" ON public.facing_directions;
CREATE POLICY "Allow admin management on facing_directions"
    ON public.facing_directions FOR ALL
    USING (public.is_admin());

DROP TRIGGER IF EXISTS trigger_facing_directions_updated_at ON public.facing_directions;
CREATE OR REPLACE TRIGGER trigger_facing_directions_updated_at
    BEFORE UPDATE ON public.facing_directions
    FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

