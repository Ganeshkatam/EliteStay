  1. Enrich localities with display_name, aliases array, search_rank, and optional population.
  2. Create amenity_categories reference table (SMALLINT PK) with domain-specific categories, icons, and slugs.
  3. Alter amenities table to add category_id FK, is_filterable, is_featured flag, and search_weight.
