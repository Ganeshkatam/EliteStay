-- 3. Alter amenities to reference category, filterability, card UI prominence, and search weighting
ALTER TABLE public.amenities
    ADD COLUMN IF NOT EXISTS category_id SMALLINT REFERENCES public.amenity_categories(id),
    ADD COLUMN IF NOT EXISTS is_filterable BOOLEAN DEFAULT true NOT NULL,
    ADD COLUMN IF NOT EXISTS is_featured BOOLEAN DEFAULT false NOT NULL,
    ADD COLUMN IF NOT EXISTS search_weight INTEGER DEFAULT 50 NOT NULL;

CREATE INDEX IF NOT EXISTS idx_amenities_category_id ON public.amenities(category_id);
CREATE INDEX IF NOT EXISTS idx_amenities_is_filterable ON public.amenities(is_filterable);
CREATE INDEX IF NOT EXISTS idx_amenities_is_featured ON public.amenities(is_featured);
CREATE INDEX IF NOT EXISTS idx_amenities_search_weight ON public.amenities(search_weight DESC);


