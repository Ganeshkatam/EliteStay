-- 1. Enrich Localities Table
ALTER TABLE public.localities
    ADD COLUMN IF NOT EXISTS display_name TEXT,
    ADD COLUMN IF NOT EXISTS aliases TEXT[] DEFAULT '{}',
    ADD COLUMN IF NOT EXISTS search_rank INTEGER DEFAULT 0 NOT NULL,
    ADD COLUMN IF NOT EXISTS population INTEGER;

-- Comment on search_rank values for standard repository understanding
COMMENT ON COLUMN public.localities.search_rank IS 'Weighting for discovery and autocomplete: 1000 = Tier-1 locality, 500 = Very popular, 100 = Normal locality, 10 = Rare locality';

CREATE INDEX IF NOT EXISTS idx_localities_search_rank ON public.localities(search_rank DESC);


-- 2. Create amenity_categories Reference Table
CREATE TABLE IF NOT EXISTS public.amenity_categories (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    description TEXT,
    icon TEXT,
    display_order INTEGER DEFAULT 0 NOT NULL,
    is_active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

ALTER TABLE public.amenity_categories ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read access on amenity_categories" ON public.amenity_categories;
CREATE POLICY "Allow public read access on amenity_categories"
    ON public.amenity_categories
    FOR SELECT
    USING (is_active = true OR public.is_admin());

DROP POLICY IF EXISTS "Allow admin management on amenity_categories" ON public.amenity_categories;
CREATE POLICY "Allow admin management on amenity_categories"
    ON public.amenity_categories
    FOR ALL
    USING (public.is_admin());

DROP TRIGGER IF EXISTS trigger_amenity_categories_updated_at ON public.amenity_categories;
CREATE OR REPLACE TRIGGER trigger_amenity_categories_updated_at
    BEFORE UPDATE ON public.amenity_categories
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

